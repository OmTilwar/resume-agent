"""Put a finished resume where Om uses it (same layout as Resume_Builder/deploy_desktop_resume.ps1):

    Resume_Builder/resumes/<slug>.tex   the source
    Resume_Builder/build/<slug>.pdf     the compiled PDF
    Desktop/Om_Tilwar_Resume.pdf        the copy to apply with (overwritten each time)

Safety:
- never overwrites a hand-written .tex in resumes/: only files this agent wrote (they carry GENERATED_MARK);
  otherwise it saves <slug>_agent.tex next to it;
- deploys only a compiled, exactly-1-page resume.
"""
from __future__ import annotations

import os
import shutil
from dataclasses import dataclass
from pathlib import Path

KIT_ROOT = Path(__file__).resolve().parents[3]          # Resume_Builder/
GENERATED_MARK = "% generated by resume-agent"
DESKTOP_NAME = "Om_Tilwar_Resume.pdf"


def desktop_dir() -> Path:
    """RESUME_DESKTOP_DIR overrides; else OneDrive's Desktop (where Windows keeps it here), else ~/Desktop."""
    if os.environ.get("RESUME_DESKTOP_DIR"):
        return Path(os.environ["RESUME_DESKTOP_DIR"])
    onedrive = Path.home() / "OneDrive" / "Desktop"
    return onedrive if onedrive.is_dir() else Path.home() / "Desktop"


@dataclass
class Deployed:
    tex: Path | None = None
    pdf: Path | None = None
    desktop: Path | None = None
    skipped: str = ""


def _existing_case_insensitive(folder: Path, name: str) -> Path:
    """Reuse the Desktop file's own spelling (om_tilwar_resume.pdf vs Om_Tilwar_Resume.pdf)."""
    if folder.is_dir():
        for p in folder.iterdir():
            if p.name.lower() == name.lower():
                return p
    return folder / name


def mark(tex: str) -> str:
    return tex if tex.startswith(GENERATED_MARK) else f"{GENERATED_MARK}\n{tex}"


def deploy(tex_path: str | Path, pdf_path: str | Path | None, pages: int | None, slug: str,
           root: Path = KIT_ROOT, desktop: Path | None = None) -> Deployed:
    out = Deployed()
    tex_path = Path(tex_path)
    resumes, build = root / "resumes", root / "build"
    resumes.mkdir(parents=True, exist_ok=True)
    build.mkdir(parents=True, exist_ok=True)

    dest = resumes / f"{slug}.tex"
    if dest.exists() and not dest.read_text(encoding="utf-8", errors="ignore").startswith(GENERATED_MARK):
        dest = resumes / f"{slug}_agent.tex"            # a hand-written resume has this name: keep it
    dest.write_text(mark(tex_path.read_text(encoding="utf-8")), encoding="utf-8")
    out.tex = dest

    if not pdf_path or not Path(pdf_path).exists():
        out.skipped = "no compiled PDF"
        return out
    if pages != 1:
        out.skipped = f"{pages} pages — fix it before applying"
        return out
    out.pdf = build / f"{dest.stem}.pdf"
    shutil.copyfile(pdf_path, out.pdf)
    target = _existing_case_insensitive(desktop or desktop_dir(), DESKTOP_NAME)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(pdf_path, target)
    out.desktop = target
    return out
